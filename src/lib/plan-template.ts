// Ядро генератора: структура документа + конструктор промпта для Anthropic API.
// Сейчас используется вручную (пишем образцы сами, чтобы проверить качество и
// структуру до подключения ключа API). После одобрения владельцем — этот же
// buildPrompt() вызывается программно в api/generate/route.ts.
//
// Архитектурное решение (2026-08-31, после разбора с владельцем): AI не придумывает
// свою нумерацию разделов и не пишет "сплошной документ". Модель возвращает
// структурированные данные под конкретные поля (см. BusinessPlanInput в
// pdf/business-plan-pdf.tsx) — нумерация, вёрстка и таблицы полностью на стороне
// PDF-шаблона, это исключает разъезжающиеся заголовки и рассинхрон нумерации.

import { RegionData } from "./regions";

export type EquipmentItem = {
  /** Название позиции — как клиент указал в анкете или в реальном КП */
  item: string;
  sum: number;
  /**
   * true — сумма взята из реального коммерческого предложения поставщика,
   * которое клиент прикладывает при подаче.
   * false — предварительная оценка (клиент ещё не получил КП), требует
   * подтверждения перед подачей. См. правило источника цифр смёты ниже.
   */
  confirmed: boolean;
};

export type AnketaInput = {
  region: RegionData;
  /** Вид деятельности своими словами, как ввёл клиент */
  activity: string;
  /** Запрашиваемая сумма, ₽ */
  requestedSum: number;
  /** Опыт клиента в этой сфере, если есть */
  experience: string;
  /** Город/населённый пункт внутри региона */
  city: string;
  /**
   * Позиции сметы. Берутся из анкеты клиента, а не изобретаются генератором —
   * см. "Правило источника цифр сметы" ниже.
   */
  equipment: EquipmentItem[];
};

// ПРАВИЛО ИСТОЧНИКА ЦИФР СМЕТЫ — почему оно появилось и что запрещает
//
// Ошибка первой версии генератора: промпт просил AI "составить смету, которая
// суммируется ровно в запрошенную сумму" — то есть предлагал модели ПРИДУМАТЬ
// правдоподобные цены на оборудование. На практике клиент прикладывает к заявке
// реальные коммерческие предложения от поставщиков, и суммы там почти никогда не
// совпадут копейка в копейку с тем, что сочинит нейросеть. Клиенту пришлось бы либо
// подгонять реальные КП под наши выдуманные цифры (это уже подделка документа),
// либо смета в нашем плане не имеет отношения к тому, что он реально принесёт.
//
// Исправление: цифры в смете — ТОЛЬКО те, что даёт клиент (реальное КП, если есть,
// или предварительная прикидка с явной пометкой "ориентировочно"). Генератор
// собирает вокруг этих цифр текст (обоснование, анализ рынка, финмодель), но
// никогда не заменяет и не подгоняет сами суммы.
//
// Финмодель (выручка/расходы по месяцам) — другое дело: это прогноз, а не факт,
// который можно подтвердить чеком. Здесь AI законно строит оценку, но она должна
// быть правдоподобной для города такого размера, не завышенной.

const ETHICAL_GUARDRAILS = `
Обязательные ограничения — соблюдать без исключений:
1. Никогда не писать и не подразумевать гарантию одобрения комиссией.
2. Смета (раздел "Смета расходов") — используй ТОЛЬКО позиции и суммы, переданные
   в разделе "Позиции сметы" ниже, дословно. Не изобретай новые позиции, не меняй
   суммы, не подгоняй итог под запрошенную сумму. Если сумма всех позиций не равна
   запрошенной сумме — прямо укажи это расхождение в тексте раздела, не скрывай и
   не исправляй самовольно. Позиции с пометкой "ориентировочно" — обозначь как
   предварительную оценку, требующую подтверждения у поставщика перед подачей.
3. Финансовая модель (выручка/расходы по месяцам) — это прогноз, можно строить как
   обоснованную оценку, но она должна быть правдоподобной для города такого
   размера, не для мегаполиса, без искусственного завышения выручки или занижения
   расходов ради красивой картинки.
4. Не включать виды деятельности, требующие лицензирования, если это не указано
   явно клиентом с подтверждением, что лицензия у него есть или оформляется.
5. Тон — деловой, простой язык, без канцелярита и без маркетинговых преувеличений.
6. Раздел "Приложения" — это перечень документов, которые физически прикладываются
   к плану (коммерческие предложения, копия паспорта и т.п.), а не пересказ разделов
   этого же документа.
`.trim();

// Структура — то, что реально спрашивают комиссии соцзащиты. Источник: анализ
// конкурентов (soc-kontrakt.tb.ru, moybiznesplan.ru) + типовые требования из
// найденных методичек. Нумерация здесь не используется — реальные номера
// проставляет PDF-шаблон (титульный лист без номера, тело — 1..11).
export const PLAN_SECTIONS = [
  "Титульный лист",
  "Резюме проекта",
  "Сведения о заявителе и обоснование выбора направления",
  "Описание товара/услуги и целевой аудитории",
  "Анализ рынка и конкурентов в городе клиента",
  "Организационный план (этапы запуска, помещение, оборудование)",
  "Смета расходов (только из переданных клиентом позиций)",
  "Финансовая модель на 12 месяцев (выручка, расходы, прибыль по месяцам)",
  "Точка безубыточности",
  "Оценка рисков",
  "SWOT-анализ",
  "Приложения (перечень физически прилагаемых документов)",
] as const;

export function buildPrompt(input: AnketaInput): string {
  const { region, activity, requestedSum, experience, city, equipment } = input;

  const equipmentSum = equipment.reduce((a, e) => a + e.sum, 0);
  const mismatch = equipmentSum !== requestedSum;

  const equipmentList = equipment
    .map(
      (e) =>
        `— ${e.item}: ${e.sum.toLocaleString("ru")} ₽` +
        (e.confirmed ? "" : " (ориентировочно, не подтверждено КП)"),
    )
    .join("\n");

  return `
Составь бизнес-план для подачи на социальный контракт на открытие бизнеса
в комиссию социальной защиты. Документ должен соответствовать требованиям
${region.name}. Верни данные под указанные ниже разделы структурированно
(по полям), без собственной нумерации заголовков — нумерацию и вёрстку
добавляет шаблон отдельно.

Данные клиента:
— Город: ${city}, ${region.name}
— Вид деятельности: ${activity}
— Запрашиваемая сумма: ${requestedSum.toLocaleString("ru")} ₽
— Опыт в сфере: ${experience || "опыта нет, планирует обучение или уже проходит"}

Позиции сметы (переданы клиентом, использовать дословно — см. правило 2 ниже):
${equipmentList}
Сумма позиций: ${equipmentSum.toLocaleString("ru")} ₽${
    mismatch
      ? ` — ВНИМАНИЕ: отличается от запрошенной суммы на ${Math.abs(
          equipmentSum - requestedSum,
        ).toLocaleString("ru")} ₽. Явно отметь это расхождение в разделе "Смета расходов".`
      : " — совпадает с запрошенной суммой."
  }

Справочные данные региона:
— Прожиточный минимум трудоспособного населения: ${region.pmTrudosposobnyh.toLocaleString("ru")} ₽/мес
  (источник: ${region.source})

Разделы документа (содержание, не нумерация):
${PLAN_SECTIONS.slice(1).join("\n")}

${ETHICAL_GUARDRAILS}
`.trim();
}
