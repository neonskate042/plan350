// Региональная база для генератора бизнес-планов под соцконтракт.
//
// Принцип: лучше пустое поле с пометкой "уточнить", чем выдуманная цифра в документе,
// который человек с доходом ниже прожиточного минимума понесёт в комиссию соцзащиты.
// Не использовать regions с verified:false в реальной генерации до проверки.

export type RegionData = {
  name: string;
  /** Прожиточный минимум трудоспособного населения на 2026 год, ₽/мес */
  pmTrudosposobnyh: number;
  /** Источник и дата, когда цифра проверена */
  source: string;
  /**
   * Максимальная сумма соцконтракта на открытие бизнеса.
   * Федеральный потолок — 350 000 ₽, но регион вправе установить свой лимит
   * (со-финансирование), поэтому без прямой проверки по конкретному региону
   * писать "до 350 000 ₽ (уточнить точный региональный лимит)".
   */
  maxSum: number;
  maxSumVerified: boolean;
  /** Прошла ли ручную проверку вся запись целиком */
  verified: boolean;
};

// ВАЖНО: соцконтракт на открытие бизнеса не действует в Москве — подтверждено
// несколькими независимыми источниками (gosuslugi, mos.ru, отраслевые статьи,
// проверено 2026-08-31). Москву не включаем в базу для этого направления вообще —
// это не забытый регион, а осознанное исключение. Если человек с московским
// регионом попадёт в анкету, интерфейс должен показать честное предупреждение,
// а не подставлять чужие цифры.
export const MOSCOW_NOT_ELIGIBLE = true;

export const regions: Record<string, RegionData> = {
  sverdlovskaya: {
    name: "Свердловская область",
    pmTrudosposobnyh: 20438,
    source: "Постановление Правительства Свердловской области на 2026 год (проверено 2026-08-31)",
    maxSum: 350000,
    maxSumVerified: false, // подтверждён только федеральный потолок, региональный лимит уточнить
    verified: true,
  },
  krasnodarsky: {
    name: "Краснодарский край",
    pmTrudosposobnyh: 19817,
    source: "gogov.ru, потребкор.ru (проверено 2026-08-31)",
    maxSum: 350000,
    maxSumVerified: false,
    verified: true,
  },

  // TODO перед расширением таргетинга рекламы на эти регионы — проверить
  // прожиточный минимум трудоспособного населения на 2026 год по официальным
  // постановлениям региональных правительств, не по агрегаторам:
  // Новосибирская область, Ростовская область, Республика Татарстан,
  // Нижегородская область, Челябинская область, Башкортостан.
};

export function getRegion(key: string): RegionData | null {
  const r = regions[key];
  return r && r.verified ? r : null;
}

/** Список для выпадающего меню в анкете — только проверенные регионы. */
export const VERIFIED_REGIONS: { key: string; name: string }[] = Object.entries(regions)
  .filter(([, r]) => r.verified)
  .map(([key, r]) => ({ key, name: r.name }));
